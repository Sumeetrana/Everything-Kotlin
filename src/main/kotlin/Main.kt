    println("Max and min values of integers is: $intergerMaxValue and $intergerMinValue respectively")

    val byteMaxValue = Byte.MAX_VALUE
    val byteMinValue = Byte.MIN_VALUE
    println("Max and min values of byte is: $byteMaxValue and $byteMinValue respectively")

    val shortMaxValue = Short.MAX_VALUE
    val shortMinValue = Short.MIN_VALUE
    println("Max and min values of short is: $shortMaxValue and $shortMinValue respectively")

    val longMaxValue = Long.MAX_VALUE
    val longMinValue = Long.MIN_VALUE
